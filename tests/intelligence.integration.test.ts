import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import express from 'express';
import pg from 'pg';
import {mountIntelligence,requireFeature,requireIntelligenceOwner,reserveAiBudget,settleAiBudget} from '../backend/intelligence';
import {mountMenuImport} from '../backend/menuImport';
import {transaction} from '../backend/database';
import {installAsyncErrors} from '../backend/http';

test('Intelligence flags, concurrent budget and transactional menu publication',async()=>{
  const connectionString=process.env.TEST_DATABASE_URL;
  assert.ok(connectionString&&new URL(connectionString).pathname.endsWith('_test'),'Banco descartável _test obrigatório.');
  const pool=new pg.Pool({connectionString});
  const suffix=crypto.randomBytes(6).toString('hex'),slug=`intel-${suffix}`,other=`intel-other-${suffix}`;
  const app=express();installAsyncErrors(app);app.use(express.json());
  const guard:express.RequestHandler=(req,res,next)=>{if(req.headers['x-test-tenant']!==req.params.slug) return void res.status(403).json({error:'Scope'});(req as any).user={sub:'intel-test-user',role:req.headers['x-test-role']||'TENANT_OWNER'};next();};
  mountIntelligence(app,pool,guard);
  mountMenuImport(app,pool,(req,res,next)=>guard(req,res,()=>requireIntelligenceOwner(req,res,next)),async()=>{});
  app.use((error:any,_req:any,res:any,_next:any)=>res.status(error.status||500).json({error:error.message}));
  const server=app.listen(0,'127.0.0.1');await new Promise<void>(resolve=>server.once('listening',resolve));
  const address=server.address();assert.ok(address&&typeof address!=='string');
  const host=`http://127.0.0.1:${address.port}`;
  async function request(path:string,body?:unknown,method='POST',role='TENANT_OWNER',tenant=slug){const response=await fetch(`${host}/api/v1/tenants/${tenant}${path}`,{method,headers:{'Content-Type':'application/json','x-test-tenant':tenant,'x-test-role':role},body:body===undefined?undefined:JSON.stringify(body)});return {status:response.status,body:await response.json()};}
  const candidates=(name:string)=>({categories:[{id:`cat-${suffix}-${name}`,name:`Categoria ${name}`}],products:[{id:`prod-${suffix}-${name}`,name:`Produto ${name}`,categoryId:`cat-${suffix}-${name}`,priceCents:1250}]});
  const publish=(preview:any,extra={})=>({version:preview.job.version,catalogHash:preview.catalogHash,diffHash:preview.diffHash,confirm:true,...extra});
  const fn=`intel_reject_${suffix}`,trigger=`intel_trigger_${suffix}`;
  let triggerCreated=false;
  try {
    await pool.query(fs.readFileSync('database/easypanel-init.sql','utf8'));
    await pool.query(fs.readFileSync('database/intelligence.sql','utf8'));
    await pool.query(fs.readFileSync('database/menu-import.sql','utf8'));
    for(const tenant of [slug,other]) await pool.query('INSERT INTO tenants(id,name,slug,phone) VALUES($1,$1,$1,$2)',[tenant,'5511999999999']);
    await assert.rejects(()=>requireFeature(pool as any,slug,'menu_import'),/desativado/);
    assert.equal((await request('/menu-imports',{filename:'bad',mimeType:'bad',contentBase64:'!'})).status,403,'disabled feature must reject before malformed source parsing');
    assert.equal((await request('/intelligence',{features:{menu_import:{released:true,enabled:true}},monthlyBudgetCents:100},'PUT')).status,403);
    for(const tenant of [slug,other]) assert.equal((await request('/intelligence',{features:{menu_import:{released:true,enabled:true}},monthlyBudgetCents:100},'PUT','SUPER_ADMIN',tenant)).status,200);
    await requireFeature(pool as any,slug,'menu_import');
    const reservations=await Promise.allSettled(['a','b'].map(key=>transaction(pool,client=>reserveAiBudget(client,slug,'menu_import',key,70))));
    assert.equal(reservations.filter(r=>r.status==='fulfilled').length,1);
    assert.equal(reservations.filter(r=>r.status==='rejected').length,1);
    const successful=reservations[0].status==='fulfilled'?'a':'b';
    assert.equal((await transaction(pool,client=>reserveAiBudget(client,slug,'menu_import',successful,70))).reused,true);
    await assert.rejects(()=>transaction(pool,client=>reserveAiBudget(client,slug,'menu_import',successful,71)),/reutilizada/);
    await transaction(pool,client=>settleAiBudget(client,slug,successful,30));
    await transaction(pool,client=>settleAiBudget(client,slug,successful,30));
    await assert.rejects(()=>transaction(pool,client=>settleAiBudget(client,slug,successful,31)),/liquidada/);
    await transaction(pool,client=>reserveAiBudget(client,slug,'menu_import','remaining',70));
    assert.equal((await pool.query('SELECT reserved_cents FROM intelligence_usage WHERE tenant_slug=$1',[slug])).rows[0].reserved_cents,100);
    await assert.rejects(()=>transaction(pool,client=>reserveAiBudget(client,slug,'menu_import','over',1)),/esgotado/);
    const first=await request('/menu-imports',candidates('primeiro'));assert.equal(first.status,201);
    const job=first.body.job.id;
    assert.equal((await request('/menu-imports',candidates('primeiro'))).body.job.id,job,'same source reuses job');
    assert.equal((await request(`/menu-imports/${job}`,undefined,'GET','TENANT_OWNER',other)).status,404);
    assert.equal((await request(`/menu-imports/${job}/publish`,publish(first.body,{version:999}))).status,409);
    const changed=await request(`/menu-imports/${job}/candidates`,{version:1,candidates:candidates('primeiro')},'PATCH');assert.equal(changed.status,200);
    assert.equal((await request(`/menu-imports/${job}/publish`,publish(first.body))).status,409,'old draft version cannot publish');
    const published=await Promise.all([request(`/menu-imports/${job}/publish`,publish(changed.body)),request(`/menu-imports/${job}/publish`,publish(changed.body))]);
    assert.deepEqual(published.map(r=>r.status),[200,200]);
    assert.equal(published.filter(r=>r.body.alreadyPublished).length,1);
    assert.equal((await pool.query("SELECT COUNT(*)::int AS count FROM menu_import_audit WHERE job_id=$1 AND action='published'",[job])).rows[0].count,1);
    const duplicateSource=candidates('duplicado');duplicateSource.products[0].name='Produto primeiro';
    const duplicates=await request('/menu-imports',duplicateSource);assert.equal(duplicates.status,201);assert.ok(duplicates.body.diff.duplicates.length);
    assert.equal((await request(`/menu-imports/${duplicates.body.job.id}/publish`,publish(duplicates.body))).status,400);
    assert.equal((await request(`/menu-imports/${duplicates.body.job.id}/publish`,publish(duplicates.body,{confirmDuplicates:true}))).status,200);
    const stale=await request('/menu-imports',candidates('obsoleto'));
    await pool.query('UPDATE products SET description=$2 WHERE tenant_slug=$1',[slug,'Alteração concorrente']);
    assert.equal((await request(`/menu-imports/${stale.body.job.id}/publish`,publish(stale.body))).status,409,'changed catalog invalidates reviewed diff');
    const rollback=await request('/menu-imports',candidates('rollback'));
    // Names contain only generated hexadecimal characters. Trigger is scoped to our tenant.
    await pool.query(`CREATE FUNCTION ${fn}() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.tenant_slug='${slug}' AND NEW.action='published' THEN RAISE EXCEPTION 'test publication failure'; END IF; RETURN NEW; END $$`);
    await pool.query(`CREATE TRIGGER ${trigger} BEFORE INSERT ON menu_import_audit FOR EACH ROW EXECUTE FUNCTION ${fn}()`);triggerCreated=true;
    const before=(await pool.query('SELECT id,name,description FROM products WHERE tenant_slug=$1 ORDER BY id',[slug])).rows;
    assert.equal((await request(`/menu-imports/${rollback.body.job.id}/publish`,publish(rollback.body))).status,500);
    assert.deepEqual((await pool.query('SELECT id,name,description FROM products WHERE tenant_slug=$1 ORDER BY id',[slug])).rows,before);
    assert.equal((await pool.query('SELECT status FROM menu_import_jobs WHERE id=$1',[rollback.body.job.id])).rows[0].status,'draft');
    assert.equal((await pool.query('SELECT 1 FROM categories WHERE tenant_slug=$1 AND id=$2',[slug,candidates('rollback').categories[0].id])).rowCount,0,'category write also rolls back');
    assert.equal((await request('/intelligence',{feature:'menu_import',enabled:false},'PATCH')).status,200);
    assert.equal((await request('/menu-imports',candidates('disabled'))).status,403);
  } finally {
    server.closeAllConnections();await new Promise<void>(resolve=>server.close(()=>resolve()));
    if(triggerCreated) await pool.query(`DROP TRIGGER IF EXISTS ${trigger} ON menu_import_audit`);
    await pool.query(`DROP FUNCTION IF EXISTS ${fn}()`);
    await pool.query('DELETE FROM products WHERE tenant_slug=ANY($1::text[])',[[slug,other]]);
    await pool.query('DELETE FROM categories WHERE tenant_slug=ANY($1::text[])',[[slug,other]]);
    await pool.query('DELETE FROM tenants WHERE slug=ANY($1::text[])',[[slug,other]]);await pool.end();
  }
});
