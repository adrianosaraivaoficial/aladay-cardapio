CREATE TABLE IF NOT EXISTS garcom_settings (
  tenant_id VARCHAR(80) PRIMARY KEY REFERENCES tenants(id) ON DELETE CASCADE,
  garcom_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS garcom_staff (
  tenant_id VARCHAR(80) NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  user_id VARCHAR(80) NOT NULL REFERENCES subscriber_users(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('waiter', 'manager', 'kitchen', 'cashier')),
  PRIMARY KEY (tenant_id, user_id)
);

CREATE TABLE IF NOT EXISTS garcom_tabs (
  id UUID PRIMARY KEY,
  tenant_id VARCHAR(80) NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  table_number INTEGER NOT NULL CHECK (table_number BETWEEN 1 AND 1000),
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
  opened_by VARCHAR(80) NOT NULL,
  opened_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (tenant_id, id)
);

CREATE UNIQUE INDEX IF NOT EXISTS garcom_single_open_tab
  ON garcom_tabs (tenant_id, table_number) WHERE status = 'open';

CREATE TABLE IF NOT EXISTS garcom_tab_open_requests (
  tenant_id VARCHAR(80) NOT NULL,
  actor_id VARCHAR(80) NOT NULL,
  idempotency_key VARCHAR(80) NOT NULL,
  tab_id UUID NOT NULL,
  PRIMARY KEY (tenant_id, actor_id, idempotency_key),
  FOREIGN KEY (tenant_id, tab_id) REFERENCES garcom_tabs(tenant_id, id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS garcom_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id VARCHAR(80) NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  actor_id VARCHAR(80) NOT NULL,
  action TEXT NOT NULL,
  tab_id UUID,
  details JSONB NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  FOREIGN KEY (tenant_id, tab_id) REFERENCES garcom_tabs(tenant_id, id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS garcom_tab_items (
  id UUID PRIMARY KEY,
  tenant_id VARCHAR(80) NOT NULL,
  tab_id UUID NOT NULL,
  snapshot JSONB NOT NULL,
  tenant_slug VARCHAR(100) NOT NULL,
  order_id VARCHAR(80),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  FOREIGN KEY (tenant_id, tenant_slug) REFERENCES tenants(id, slug) ON DELETE CASCADE,
  FOREIGN KEY (order_id, tenant_slug) REFERENCES orders(id, tenant_slug) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id, tab_id) REFERENCES garcom_tabs(tenant_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS garcom_tab_items_scope ON garcom_tab_items (tenant_id, tab_id, created_at, id);

CREATE INDEX IF NOT EXISTS garcom_tab_items_order ON garcom_tab_items (order_id) WHERE order_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS garcom_tab_commands (
  tenant_id VARCHAR(80) NOT NULL,
  tab_id UUID NOT NULL,
  actor_id VARCHAR(80) NOT NULL,
  idempotency_key VARCHAR(80) NOT NULL,
  request_hash TEXT NOT NULL,
  result JSONB NOT NULL,
  PRIMARY KEY (tenant_id, tab_id, actor_id, idempotency_key),
  FOREIGN KEY (tenant_id, tab_id) REFERENCES garcom_tabs(tenant_id, id) ON DELETE CASCADE
);
